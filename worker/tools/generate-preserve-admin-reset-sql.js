// Generates a deliberate, terminal-operated client reset SQL file.
//
// It removes operational/client setup data while preserving every ADMIN row,
// the configured subscription/branding settings, system chart of accounts,
// WHT rate definitions and the NAFDAC reference catalog. It is for a NEW or
// explicitly retired client deployment only — never a substitute for a backup
// or retention review.
//
// The generator requires an explicit environment confirmation so a casual
// `npm run` cannot create a destructive script by accident:
//   $env:PHARMARIDGE_CONFIRM_RESET = 'RESET_CLIENT_DATA'
//   npm run db:generate:preserve-admin-reset
//
// Output: worker/client-admin-reset.sql (gitignored). Review it, take/export
// a backup, then run it once with Wrangler against the intended D1 database.
const fs = require('fs');
const path = require('path');

if (process.env.PHARMARIDGE_CONFIRM_RESET !== 'RESET_CLIENT_DATA') {
  console.error('Refusing to create reset SQL. Set PHARMARIDGE_CONFIRM_RESET to RESET_CLIENT_DATA for this terminal session.');
  process.exit(1);
}

const sql = `-- CLIENT RESET — PRESERVES ADMIN ACCOUNT(S) ONLY
-- Generated by tools/generate-preserve-admin-reset-sql.js.
--
-- Preconditions:
--   1. A tested backup/export exists OUTSIDE this repository.
--   2. You verified the target D1 database name and Cloudflare account.
--   3. At least one ADMIN row exists. This script preserves ADMIN rows only.
--   4. You understand this permanently removes client operational/setup data.
--
-- This is NOT a D1 database drop. It preserves migrations, nafdac_catalog,
-- gl_accounts, wht_rates and client_settings so the preserved Admin can create
-- a new Owner through the normal application onboarding flow.

-- PRE-CHECK: this must return one or more active Admin rows before continuing.
-- Run this query separately in the terminal as well; SQLite RAISE() is only
-- legal inside triggers, so a plain SQL batch cannot safely abort here.
SELECT username, full_name FROM users
WHERE role = 'ADMIN' AND is_deleted = 0 AND is_active = 1;

-- Child-first deletion order: D1 enforces foreign keys.
DELETE FROM controlled_substance_register;
DELETE FROM prescriptions;
DELETE FROM sale_payments;
DELETE FROM sale_items;
DELETE FROM sales;
DELETE FROM debtor_ledger;
DELETE FROM change_owed;
DELETE FROM branch_safe_ledger;
DELETE FROM creditor_ledger;
DELETE FROM expenses;
DELETE FROM wht_entries;
DELETE FROM gl_journal_lines;
DELETE FROM gl_journal_entries;
DELETE FROM stocktake_lines;
DELETE FROM stocktake_sessions;
DELETE FROM stock_adjustments;
DELETE FROM stock_transfers;
DELETE FROM staff_attendance;
DELETE FROM till_sessions;
DELETE FROM stock_batches;
DELETE FROM purchase_order_receipts;
DELETE FROM purchase_order_items;
DELETE FROM purchase_orders;
DELETE FROM product_price_overrides;
DELETE FROM customers;
DELETE FROM suppliers;
DELETE FROM branch_devices;
DELETE FROM pending_user_transfers;
DELETE FROM user_assignment_history;
DELETE FROM idempotency_keys;
DELETE FROM user_sessions;
DELETE FROM login_attempts;
DELETE FROM sync_conflicts;
DELETE FROM sync_change_log;
DELETE FROM branch_sync_status;
DELETE FROM data_cleanup_log;

-- Clear client people/branches/products, preserving only deployment Admins.
UPDATE client_settings
SET updated_by = NULL,
    data_reset_at = NULL,
    updated_at = datetime('now')
WHERE id = 1;
DELETE FROM users WHERE role != 'ADMIN';
DELETE FROM branches;
DELETE FROM products;

-- POST-CHECK: execute the Admin query from the runbook after this batch.
`;

const output = path.join(__dirname, '..', 'client-admin-reset.sql');
fs.writeFileSync(output, sql, { mode: 0o600 });
console.log(`Created ${output}`);
console.log('Review it, back up first, execute it once against the intended remote D1 database, then delete it.');
