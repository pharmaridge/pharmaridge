// Generates a two-step full D1 schema-format procedure for a deliberately
// retired deployment. It preserves only the existing active ADMIN row(s),
// never their plaintext secret. The caller must separately verify an active
// Admin exists before the destructive first step.
const fs = require('fs');
const path = require('path');

if (process.env.PHARMARIDGE_CONFIRM_SCHEMA_RESET !== 'FORMAT_SCHEMA_PRESERVE_ADMIN') {
  console.error('Refusing to generate schema-format SQL. Set PHARMARIDGE_CONFIRM_SCHEMA_RESET to FORMAT_SCHEMA_PRESERVE_ADMIN for this terminal session.');
  process.exit(1);
}

const views = [
  'v_change_owed_outstanding', 'v_branch_safe_balances', 'v_daily_sales_by_branch',
  'v_daily_sales_total', 'v_stock_value_by_branch', 'v_expiry_alerts',
  'v_low_stock_alerts', 'v_debtor_balances', 'v_creditor_balances',
  'v_branch_sync_overview', 'v_license_expiry_alerts', 'v_void_audit_by_user',
  'v_gl_account_balances', 'v_gl_account_balances_total',
];
const tables = [
  // Child/operational tables first. Foreign keys are also disabled for the
  // batch because the purpose is an explicit full format, not a partial clean.
  'controlled_substance_register', 'prescriptions', 'sale_payments', 'sale_items',
  'sales', 'debtor_ledger', 'change_owed', 'branch_safe_ledger', 'creditor_ledger',
  'expenses', 'wht_entries', 'gl_journal_lines', 'gl_journal_entries',
  'stocktake_lines', 'stocktake_sessions', 'stock_adjustments', 'stock_transfers',
  'staff_attendance', 'till_sessions', 'stock_batches', 'purchase_order_receipts',
  'purchase_order_items', 'purchase_orders', 'product_price_overrides', 'customers',
  'suppliers', 'branch_devices', 'pending_user_transfers', 'user_assignment_history',
  'user_sessions', 'idempotency_keys', 'login_attempts', 'sync_conflicts',
  'sync_change_log', 'branch_sync_status', 'data_cleanup_log', 'wht_rates',
  'gl_accounts', 'products', 'nafdac_catalog', 'client_settings', 'users', 'branches',
];

const formatSql = `-- FULL D1 FORMAT — PRESERVES ACTIVE ADMIN ROW(S) IN A TEMPORARY TABLE ONLY
-- Generated by tools/generate-preserve-admin-schema-reset-sql.js.
--
-- Before this file: verify an active Admin exists. Back up required records.
-- After this file: apply the two baseline migrations, then execute the paired
-- restore file exactly once. Do not insert a shared/default Admin password.

CREATE TABLE _pharmaridge_admin_preserve AS
SELECT * FROM users
WHERE role = 'ADMIN' AND is_active = 1 AND is_deleted = 0;

PRAGMA foreign_keys = OFF;
DROP TRIGGER IF EXISTS trg_gl_journal_entry_must_balance_before_posting;
${views.map((name) => `DROP VIEW IF EXISTS ${name};`).join('\n')}
${tables.map((name) => `DROP TABLE IF EXISTS ${name};`).join('\n')}
-- Wrangler reads this tracking table to decide that the new consolidated
-- baseline migrations must be applied after the format.
DELETE FROM d1_migrations;
PRAGMA foreign_keys = ON;
`;

const restoreSql = `-- ADMIN RESTORE — RUN ONLY AFTER FRESH 0001 + 0002 MIGRATIONS SUCCEED
-- Restores the pre-format active Admin row(s), including existing PBKDF2 hash,
-- without exposing or changing any plaintext credential.
INSERT INTO users SELECT * FROM _pharmaridge_admin_preserve;
DROP TABLE _pharmaridge_admin_preserve;
`;

const root = path.join(__dirname, '..');
const formatFile = path.join(root, 'schema-admin-format.sql');
const restoreFile = path.join(root, 'schema-admin-restore.sql');
fs.writeFileSync(formatFile, formatSql, { mode: 0o600 });
fs.writeFileSync(restoreFile, restoreSql, { mode: 0o600 });
console.log(`Created ${formatFile} and ${restoreFile}`);
console.log('Back up and verify an active Admin first. Run format → migrations → restore, then delete both files.');
